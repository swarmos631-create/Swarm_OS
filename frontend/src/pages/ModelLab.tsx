import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";

import { api, ApiError } from "../api/client";
import type { ModelInfo, ModelVersionInfo, RuntimeProvider } from "../api/types";
import { ConfirmDialog, Dialog, EmptyState, ErrorState, LoadingBlock, Panel, StatusBadge } from "../components/ui";
import { ago, fmtNum, titleCase } from "../lib/format";
import { Icon } from "../lib/icons";
import { useSession } from "../state/session";
import { useOnline, useToast } from "../state/ui";

export default function ModelLabPage() {
  const { can } = useSession();
  const online = useOnline();
  const toast = useToast();
  const qc = useQueryClient();
  const [report, setReport] = useState<{ name: string; version: string } | null>(null);
  const [confirm, setConfirm] = useState<{ kind: "promote" | "rollback"; name: string; version?: string; force?: boolean } | null>(null);
  const q = useQuery({
    queryKey: ["models"],
    queryFn: () => api<{ items: ModelInfo[]; runtime: { providers: RuntimeProvider[]; llm_narratives_enabled: boolean; external_llm_providers: string } }>("/models"),
    refetchInterval: (query) => (query.state.data?.items.some((m) => m.latest_job && ["queued", "running"].includes(m.latest_job.status)) ? 2000 : 20_000),
  });
  const train = useMutation({
    mutationFn: (name: string) => api(`/models/${name}/train`, { method: "POST", body: { promote_if_better: true } }),
    onSuccess: () => { toast("info", "Training job queued"); void qc.invalidateQueries({ queryKey: ["models"] }); },
    onError: (e) => toast("err", e instanceof ApiError ? e.message : "Could not start training"),
  });
  const act = useMutation({
    mutationFn: (c: NonNullable<typeof confirm>) => c.kind === "promote"
      ? api(`/models/${c.name}/versions/${c.version}/promote`, { method: "POST", body: { force: !!c.force } })
      : api(`/models/${c.name}/rollback`, { method: "POST" }),
    onSuccess: () => { toast("ok", "Model registry updated"); setConfirm(null); void qc.invalidateQueries({ queryKey: ["models"] }); },
    onError: (e) => toast("err", e instanceof ApiError ? e.message : "Registry update failed"),
  });

  return (
    <>
      <div className="page-head">
        <div><h1>Model Lab</h1><p>Locally trained models, evaluation gates, promotion and rollback. CPU-first; no external LLM APIs are used anywhere in SwarmOS.</p></div>
      </div>
      {q.error ? <ErrorState error={q.error} /> : !q.data ? <LoadingBlock rows={8} /> : (
        <>
          <Panel title="Local model runtime" icon="cube">
            <div className="grid cols-4">
              {q.data.runtime.providers.map((p) => (
                <div key={p.id} className="panel" style={{ padding: 12 }}>
                  <div className="row between"><b>{p.id}</b><StatusBadge s={p.available ? "connected" : "unavailable"} label={p.available ? "Available" : "Unavailable"} /></div>
                  <div className="xs faint">{p.kind}{p.endpoint ? ` · ${p.endpoint}` : ""}</div>
                  <p className="small muted" style={{ marginTop: 6 }}>{p.detail}</p>
                </div>
              ))}
            </div>
            <p className="xs faint" style={{ marginTop: 10 }}>External LLM providers: {q.data.runtime.external_llm_providers}. Local LLM narratives: {q.data.runtime.llm_narratives_enabled ? "enabled" : "disabled (deterministic templates in use)"}.</p>
          </Panel>
          <div className="notice warn"><Icon name="alert" /><span>All models below are trained on <b>synthetic</b> datasets generated by SwarmOS. Their metrics prove the pipeline works end to end, not real-world accuracy. Retrain on authorised city data before operational use.</span></div>
          {q.data.items.map((m) => (
            <Panel key={m.model_name} title={m.model_name} icon="models" actions={<>
              {m.promoted ? <StatusBadge s="promoted" label={`Promoted ${m.promoted.version.slice(0, 17)}`} /> : <StatusBadge s="unavailable" label="No promoted version" />}
              {can("admin") && <button className="btn sm" disabled={!online || train.isPending || (m.latest_job != null && ["queued", "running"].includes(m.latest_job.status))} onClick={() => train.mutate(m.model_name)}><Icon name="play" />Train</button>}
              {can("admin") && m.versions.some((v) => v.promoted_at && v.status !== "promoted") && <button className="btn sm" disabled={!online} onClick={() => setConfirm({ kind: "rollback", name: m.model_name })}>Roll back</button>}
            </>}>
              <div className="stack-lg">
                <p className="small muted">{m.description} · {titleCase(m.task_type)} · <span className="mono">{m.algorithm}</span> · used by {m.used_by.join(", ")}</p>
                <p className="xs faint">Gate: {m.gate.metric} must {m.gate.lower_is_better ? `be ≥${(m.gate.margin ?? 0) * 100}% lower than` : `beat by ${m.gate.margin ?? 0}`} the baseline{m.gate.min_value != null ? ` and reach ≥ ${m.gate.min_value}` : ""}.</p>
                {m.latest_job && <div className="row small"><StatusBadge s={m.latest_job.status} /><span className="faint">Last training job {ago(m.latest_job.created_at)}{m.latest_job.error ? ` — ${m.latest_job.error}` : ""}</span></div>}
                {m.versions.length === 0 ? <EmptyState title="Never trained">{can("admin") ? "Use Train to run the pipeline on the synthetic fixture dataset." : "An admin can train this model."}</EmptyState> : (
                  <div className="table-wrap"><table className="table">
                    <thead><tr><th>Version</th><th>Metrics (model vs baseline)</th><th>Gate</th><th>Status</th><th>Trained</th><th /></tr></thead>
                    <tbody>{m.versions.map((v) => <VersionRow key={v.id} v={v} canAdmin={can("admin")} online={online}
                      onReport={() => setReport({ name: m.model_name, version: v.version })}
                      onPromote={(force) => setConfirm({ kind: "promote", name: m.model_name, version: v.version, force })} />)}</tbody>
                  </table></div>
                )}
              </div>
            </Panel>
          ))}
        </>
      )}
      {report && <ReportDialog {...report} onClose={() => setReport(null)} />}
      {confirm && (
        <ConfirmDialog title={confirm.kind === "promote" ? "Promote model version" : "Roll back model"} confirmLabel={confirm.kind === "promote" ? (confirm.force ? "Force promote" : "Promote") : "Roll back"}
          danger={confirm.force || confirm.kind === "rollback"} busy={act.isPending} onClose={() => setConfirm(null)} onConfirm={() => act.mutate(confirm)}
          body={confirm.kind === "promote"
            ? <p>Agents will start using <b>{confirm.name}@{confirm.version}</b> immediately.{confirm.force && " This version FAILED its evaluation gate; forcing promotion is audited."}</p>
            : <p>Re-promote the previously promoted version of <b>{confirm.name}</b>. This is audited.</p>} />
      )}
    </>
  );
}

function VersionRow({ v, canAdmin, online, onReport, onPromote }: { v: ModelVersionInfo; canAdmin: boolean; online: boolean; onReport: () => void; onPromote: (force: boolean) => void }) {
  return (
    <tr>
      <td className="mono xs">{v.version}</td>
      <td className="small">{Object.entries(v.metrics).map(([k, val]) => (
        <div key={k}><span className="faint">{k}</span> <b className="num">{fmtNum(val, 3)}</b>{v.baseline_metrics[k] != null && <span className="faint"> vs {fmtNum(v.baseline_metrics[k] as number, 3)}</span>}</div>))}</td>
      <td><StatusBadge s={v.passed_gate ? "succeeded" : "failed"} label={v.passed_gate ? "Passed" : "Failed"} /></td>
      <td><StatusBadge s={v.status} /></td>
      <td className="small faint">{ago(v.created_at)}</td>
      <td><div className="row">
        <button className="btn sm ghost" onClick={onReport}><Icon name="doc" />Report</button>
        {canAdmin && v.status !== "promoted" && <button className="btn sm" disabled={!online} onClick={() => onPromote(!v.passed_gate)}>{v.passed_gate ? "Promote" : "Force…"}</button>}
      </div></td>
    </tr>
  );
}

function ReportDialog({ name, version, onClose }: { name: string; version: string; onClose: () => void }) {
  const q = useQuery({ queryKey: ["report", name, version], queryFn: () => api<{ markdown: string }>(`/models/${name}/versions/${version}/report`) });
  return (
    <Dialog title={`Evaluation report — ${name}`} onClose={onClose} wide>
      {q.error ? <ErrorState error={q.error} /> : !q.data ? <LoadingBlock /> : <pre className="json" style={{ whiteSpace: "pre-wrap", maxHeight: "60vh" }}>{q.data.markdown}</pre>}
    </Dialog>
  );
}
